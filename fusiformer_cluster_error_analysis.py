def safe_r2(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    if len(y_true) < 2 or float(np.var(y_true)) <= 1e-15:
        return float("nan")
    return float(r2_score(y_true, y_pred))


def safe_corr(
    a: np.ndarray,
    b: np.ndarray,
    method: str,
) -> float:
    mask = np.isfinite(a) & np.isfinite(b)
    if int(mask.sum()) < 3:
        return float("nan")
    aa = a[mask]
    bb = b[mask]
    if float(np.std(aa)) <= 1e-15 or float(np.std(bb)) <= 1e-15:
        return float("nan")
    if method == "pearson":
        return float(pearsonr(aa, bb)[0])
    if method == "spearman":
        return float(spearmanr(aa, bb)[0])
    raise ValueError(method)


def summarize_group(df: pd.DataFrame, label: str) -> Dict[str, Any]:
    y = df["y_true"].to_numpy(float)
    p = df["y_pred"].to_numpy(float)
    e = df["error"].to_numpy(float)
    ae = df["abs_error"].to_numpy(float)

    return {
        "group": label,
        "n": int(len(df)),
        "mean_true": float(np.mean(y)),
        "std_true": float(np.std(y, ddof=0)),
        "mean_pred": float(np.mean(p)),
        "std_pred": float(np.std(p, ddof=0)),
        "bias_mean_error": float(np.mean(e)),
        "mae": float(np.mean(ae)),
        "rmse": float(np.sqrt(np.mean(e * e))),
        "median_abs_error": float(np.median(ae)),
        "p90_abs_error": float(np.percentile(ae, 90)),
        "p95_abs_error": float(np.percentile(ae, 95)),
        "p99_abs_error": float(np.percentile(ae, 99)),
        "max_abs_error": float(np.max(ae)),
        "r2_within_group": safe_r2(y, p),
        "pearson_true_pred": safe_corr(y, p, "pearson"),
        "spearman_true_pred": safe_corr(y, p, "spearman"),
    }


