"""
Fusiformer cluster-wise prediction error analysis
==================================================

Purpose
-------
Evaluate the trained Base Fusiformer on a held-out split (test by default),
then analyze prediction performance within the previously obtained
Fusiformer latent clusters.

Primary outputs
---------------
1. Per-sample:
   - y_true
   - y_pred
   - signed error = y_pred - y_true
   - absolute error
   - latent cluster
   - PCA-1 / PCA-2 coordinates of graph-only graph_out
   - distance to cluster centroid / routing confidence

2. Per-cluster:
   - MAE / RMSE / bias / MedAE / P90/P95 absolute error / R^2
   - sample count and target/prediction statistics

3. Visualizations:
   - latent PCA colored by signed prediction error
   - latent PCA colored by absolute error
   - error / absolute-error boxplots by cluster
   - per-cluster MAE/RMSE
   - true-vs-prediction by cluster
   - error-vs-e_form / abs-error-vs-e_form
   - abs-error-vs-centroid-distance

Important
---------
- Default EVAL_SPLIT="test": model performance is evaluated on the held-out test
  split reproduced with the project's split_train_val_test() (split_seed=7).
- Existing cluster assignments are loaded from the clustering experiment.
- Existing graph-only graph_out cache is reused for PCA/error maps.
- PREDICTION_MODE="checkpoint" follows checkpoint["training_config"]["use_text"].
  If the Base Fusiformer was trained/evaluated with cached text embeddings,
  prediction uses them; cluster locations remain the graph-only latent space.
- This script does NOT train or fine-tune any model.
"""

