def infer_latent_preprocess(assignments_path: Path) -> str:
    mode = LATENT_PREPROCESS.strip().lower()
    if mode != "auto":
        return mode

    run_dir = assignments_path.parent.parent
    config_path = run_dir / "analysis_config.json"
    if config_path.is_file():
        try:
            with config_path.open("r", encoding="utf-8") as f:
                cfg = json.load(f)
            candidate = str(cfg.get("latent_preprocess", "l2")).strip().lower()
            if candidate in {"l2", "none", "standardize"}:
                print(f"Latent preprocess inferred from analysis_config.json: {candidate}")
                return candidate
        except Exception as exc:
            print(f"[Warning] Could not read {config_path}: {exc}")

    print("[Warning] Falling back to LATENT_PREPROCESS='l2'.")
    return "l2"


def preprocess_rows_l2(x: np.ndarray) -> np.ndarray:
    x = np.asarray(x, dtype=np.float32)
    norm = np.linalg.norm(x, axis=1, keepdims=True)
    norm = np.maximum(norm, 1e-12)
    return x / norm


def fit_latent_preprocessor(
    cache: np.ndarray,
    mode: str,
    fit_idx: np.ndarray,
) -> Dict[str, Any]:
    mode = mode.lower()
    if mode == "l2":
        return {"mode": "l2"}
    if mode == "none":
        return {"mode": "none"}
    if mode == "standardize":
        sample = np.asarray(cache[fit_idx], dtype=np.float64)
        mean = sample.mean(axis=0)
        std = sample.std(axis=0)
        std = np.where(std < 1e-12, 1.0, std)
        return {"mode": "standardize", "mean": mean, "std": std}
    raise ValueError("latent preprocess must be l2/none/standardize.")


def transform_latent(x: np.ndarray, prep: Dict[str, Any]) -> np.ndarray:
    x = np.asarray(x, dtype=np.float32)
    mode = prep["mode"]
    if mode == "l2":
        return preprocess_rows_l2(x)
    if mode == "none":
        return x
    if mode == "standardize":
        return ((x - prep["mean"]) / prep["std"]).astype(np.float32)
    raise ValueError(mode)


def build_pca_and_coordinates(
    graph_cache_path: Path,
    eval_indices: Sequence[int],
    train_indices: Sequence[int],
    assignments_df: pd.DataFrame,
    cluster_col: str,
    preprocess_mode: str,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, Dict[str, Any]]:
    cache = np.load(graph_cache_path, mmap_mode="r")
    n = int(cache.shape[0])

    rng = np.random.default_rng(PCA_RANDOM_SEED)
    fit_n = min(PCA_FIT_SAMPLE_SIZE, n)
    fit_idx = np.sort(rng.choice(n, size=fit_n, replace=False))

    prep = fit_latent_preprocessor(cache, preprocess_mode, fit_idx)
    fit_x = transform_latent(cache[fit_idx], prep)

    pca = PCA(n_components=2, random_state=PCA_RANDOM_SEED)
    fit_xy = pca.fit_transform(fit_x)

    eval_idx_arr = np.asarray(eval_indices, dtype=int)
    eval_x = transform_latent(cache[eval_idx_arr], prep)
    eval_xy = pca.transform(eval_x)

    # Train centroids for routing-distance diagnostics.
    assignment_lookup = assignments_df.set_index("index")[cluster_col]
    train_idx_arr = np.asarray(train_indices, dtype=int)
    train_labels = (
        assignment_lookup.loc[train_idx_arr].to_numpy(dtype=int)
        if len(train_idx_arr)
        else np.array([], dtype=int)
    )
    train_x = transform_latent(cache[train_idx_arr], prep) if len(train_idx_arr) else None

    clusters = sorted(assignments_df[cluster_col].astype(int).unique().tolist())
    centroids: Dict[int, np.ndarray] = {}
    for c in clusters:
        if train_x is None:
            continue
        mask = train_labels == c
        if np.any(mask):
            centroids[c] = np.mean(train_x[mask], axis=0)

    eval_labels = assignment_lookup.loc[eval_idx_arr].to_numpy(dtype=int)

    if centroids:
        centroid_matrix = np.stack([centroids[c] for c in clusters], axis=0)
        # [N_eval, K]
        dmat = np.sqrt(
            np.maximum(
                np.sum((eval_x[:, None, :] - centroid_matrix[None, :, :]) ** 2, axis=2),
                0.0,
            )
        )
        sorted_d = np.sort(dmat, axis=1)
        nearest_distance = sorted_d[:, 0]
        second_distance = sorted_d[:, 1] if dmat.shape[1] > 1 else sorted_d[:, 0]
        routing_confidence = (
            (second_distance - nearest_distance)
            / np.maximum(second_distance, 1e-12)
        )
        own_cluster_distance = np.array(
            [
                np.linalg.norm(eval_x[i] - centroids[int(eval_labels[i])])
                if int(eval_labels[i]) in centroids
                else np.nan
                for i in range(len(eval_x))
            ],
            dtype=np.float64,
        )
    else:
        nearest_distance = np.full(len(eval_x), np.nan)
        routing_confidence = np.full(len(eval_x), np.nan)
        own_cluster_distance = np.full(len(eval_x), np.nan)

    info = {
        "pca_fit_n": int(fit_n),
        "pca_explained_variance_ratio": [
            float(v) for v in pca.explained_variance_ratio_
        ],
        "latent_preprocess": preprocess_mode,
    }

    del cache
    return (
        eval_xy,
        fit_xy,
        fit_idx,
        own_cluster_distance,
        routing_confidence,
        info,
    )


