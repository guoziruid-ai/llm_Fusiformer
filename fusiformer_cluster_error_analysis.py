def extract_model_state(checkpoint: Any) -> Tuple[Dict[str, torch.Tensor], Dict[str, Any]]:
    if not isinstance(checkpoint, dict):
        raise TypeError("Checkpoint must be a dict/state_dict.")

    training_config = checkpoint.get("training_config") or checkpoint.get("run_config") or {}

    if "model_state_dict" in checkpoint:
        state = checkpoint["model_state_dict"]
    elif "model" in checkpoint:
        state = checkpoint["model"]
    elif "state_dict" in checkpoint:
        state = checkpoint["state_dict"]
    elif checkpoint and all(torch.is_tensor(v) for v in checkpoint.values()):
        state = checkpoint
    else:
        raise KeyError("Checkpoint does not contain model_state_dict/model/state_dict.")

    if state and all(str(k).startswith("module.") for k in state.keys()):
        state = {str(k)[len("module."):]: v for k, v in state.items()}

    return dict(state), dict(training_config)


def infer_depth_from_state(state: Dict[str, torch.Tensor]) -> Optional[int]:
    indices: List[int] = []
    for key in state:
        if key.startswith("blocks."):
            parts = key.split(".")
            if len(parts) > 1 and parts[1].isdigit():
                indices.append(int(parts[1]))
    return max(indices) + 1 if indices else None


def _config_int(
    training_config: Dict[str, Any],
    name: str,
    override: Optional[int],
    fallback: Optional[int],
) -> int:
    if override is not None:
        return int(override)
    if training_config.get(name) is not None:
        return int(training_config[name])
    if fallback is not None:
        return int(fallback)
    raise ValueError(f"Cannot infer model parameter {name!r}.")


def infer_model_config(
    state: Dict[str, torch.Tensor],
    training_config: Dict[str, Any],
) -> Dict[str, int]:
    atom_w = state.get("atom_embedding.weight")
    edge_w = state.get("edge_embedding.1.weight")
    angle_w = state.get("angle_embedding.1.weight")
    text_w = state.get("text_proj.0.weight")

    inferred_embed = int(atom_w.shape[1]) if atom_w is not None else None
    inferred_edge = int(edge_w.shape[1]) if edge_w is not None else None
    inferred_angle = int(angle_w.shape[1]) if angle_w is not None else None
    inferred_text = int(text_w.shape[1]) if text_w is not None else None

    return {
        "depth": _config_int(
            training_config, "depth", DEPTH_OVERRIDE, infer_depth_from_state(state) or 4
        ),
        "edge_input_dim": _config_int(
            training_config, "edge_input_dim", EDGE_INPUT_DIM_OVERRIDE, inferred_edge or 80
        ),
        "triplet_input_dim": _config_int(
            training_config,
            "triplet_input_dim",
            TRIPLET_INPUT_DIM_OVERRIDE,
            inferred_angle or 40,
        ),
        "embed_dim": _config_int(
            training_config, "embed_dim", EMBED_DIM_OVERRIDE, inferred_embed or 128
        ),
        "num_heads": _config_int(
            training_config, "num_heads", NUM_HEADS_OVERRIDE, 4
        ),
        "text_dim": _config_int(
            training_config, "text_dim", TEXT_DIM_OVERRIDE, inferred_text or 1536
        ),
    }


def build_model(
    checkpoint: Any,
    device: torch.device,
) -> Tuple[torch.nn.Module, Dict[str, Any], Dict[str, Any]]:
    state, training_config = extract_model_state(checkpoint)
    cfg = infer_model_config(state, training_config)

    model = TextGuidedFusiformer(
        targets=[str(training_config.get("target", "e_form"))],
        depth=cfg["depth"],
        edge_input_dim=cfg["edge_input_dim"],
        triplet_input_dim=cfg["triplet_input_dim"],
        embed_dim=cfg["embed_dim"],
        num_heads=cfg["num_heads"],
        text_dim=cfg["text_dim"],
        qwen_model_name="unused_cached_or_bypass_mode",
        freeze_qwen=True,
        load_qwen=False,
    )

    filtered_state = {
        key: value
        for key, value in state.items()
        if not str(key).startswith("qwen.")
    }
    incompatible = model.load_state_dict(filtered_state, strict=False)
    missing = [k for k in incompatible.missing_keys if not k.startswith("qwen.")]
    unexpected = [k for k in incompatible.unexpected_keys if not k.startswith("qwen.")]
    if missing or unexpected:
        raise RuntimeError(
            "Checkpoint/model mismatch.\n"
            f"Missing keys: {missing[:30]}\n"
            f"Unexpected keys: {unexpected[:30]}"
        )

    model.use_precomputed_text_embeddings = True
    model.freeze_qwen = True
    model = model.to(device)
    model.eval()
    return model, training_config, cfg


def normalize_targets(targets: Any, device: torch.device) -> torch.Tensor:
    if isinstance(targets, list):
        targets = torch.cat(targets, dim=-1)
    elif isinstance(targets, tuple):
        targets = torch.cat(list(targets), dim=-1)
    return targets.to(device, non_blocking=True)


def normalize_outputs(outputs: Any) -> torch.Tensor:
    if isinstance(outputs, (list, tuple)):
        return torch.cat(list(outputs), dim=-1)
    return outputs


