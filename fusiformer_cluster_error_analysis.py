def plot_centroid_distance(
    sample_df: pd.DataFrame,
    out_dir: Path,
) -> pd.DataFrame:
    valid = sample_df[
        np.isfinite(sample_df["own_cluster_centroid_distance"])
    ].copy()
    if len(valid) < 3:
        return pd.DataFrame()

    rows: List[Dict[str, Any]] = []

    def add_corr(label: str, sub: pd.DataFrame) -> None:
        x = sub["own_cluster_centroid_distance"].to_numpy(float)
        y = sub["abs_error"].to_numpy(float)
        rows.append(
            {
                "group": label,
                "n": len(sub),
                "spearman_abs_error_vs_centroid_distance": safe_corr(
                    x, y, "spearman"
                ),
                "pearson_abs_error_vs_centroid_distance": safe_corr(
                    x, y, "pearson"
                ),
            }
        )

    add_corr("ALL", valid)
    for c in sorted(valid["cluster"].unique()):
        add_corr(f"G{int(c)}", valid[valid["cluster"] == c])

    corr_df = pd.DataFrame(rows)

    idx = _plot_indices(len(valid))
    sub = valid.iloc[idx]
    fig, ax = plt.subplots(figsize=(7.6, 5.6))
    sc = ax.scatter(
        sub["own_cluster_centroid_distance"],
        sub["abs_error"],
        c=sub["cluster"],
        s=8,
        alpha=0.60,
    )
    ax.set_xlabel("Distance to own train-cluster centroid")
    ax.set_ylabel("Absolute error (eV/atom)")
    ax.set_title("Prediction error vs latent distance from cluster center")
    plt.colorbar(sc, ax=ax, label="latent cluster")
    _save(fig, out_dir / "abs_error_vs_centroid_distance.png")
    return corr_df


