@torch.no_grad()
def predict(
    model: torch.nn.Module,
    dataset: CachedCrystalGraphDataset,
    device: torch.device,
    use_text: bool,
) -> Tuple[np.ndarray, np.ndarray]:
    kwargs: Dict[str, Any] = dict(
        batch_size=BATCH_SIZE,
        shuffle=False,
        drop_last=False,
        num_workers=NUM_WORKERS,
        pin_memory=PIN_MEMORY and device.type == "cuda",
        collate_fn=dataset.collect(),
    )
    if NUM_WORKERS > 0:
        kwargs["persistent_workers"] = True

    loader = torch.utils.data.DataLoader(dataset, **kwargs)
    y_true_chunks: List[np.ndarray] = []
    y_pred_chunks: List[np.ndarray] = []

    model.eval()
    amp_enabled = bool(USE_AMP and device.type == "cuda")

    for batch_i, (inputs, targets) in enumerate(loader):
        inputs = to_device(inputs, device)
        targets = normalize_targets(targets, device)

        if use_text:
            inputs["text_mode"] = "normal"
        else:
            inputs["text_mode"] = "bypass"
            inputs["text"] = None
            inputs["text_emb"] = None

        if amp_enabled:
            with torch.amp.autocast(device_type="cuda", enabled=True):
                outputs = normalize_outputs(model(inputs))
        else:
            outputs = normalize_outputs(model(inputs))

        y_true_chunks.append(
            targets.detach().float().cpu().numpy().reshape(-1)
        )
        y_pred_chunks.append(
            outputs.detach().float().cpu().numpy().reshape(-1)
        )

        if (batch_i + 1) % 100 == 0 or (batch_i + 1) == len(loader):
            done = min((batch_i + 1) * BATCH_SIZE, len(dataset))
            print(f"  predicted {done:,}/{len(dataset):,}")

    return (
        np.concatenate(y_true_chunks).astype(np.float64),
        np.concatenate(y_pred_chunks).astype(np.float64),
    )


