def build_eval_dataset(
    data: List[Dict[str, Any]],
    indices: Sequence[int],
    target_name: str,
    text_cache_path: Optional[Path],
    use_text: bool,
) -> CachedCrystalGraphDataset:
    if use_text:
        if text_cache_path is None or not text_cache_path.is_file():
            raise FileNotFoundError(
                "Text-guided prediction requires the pooled Qwen embedding cache. "
                "Set TEXT_EMBEDDING_CACHE_PATH_OVERRIDE."
            )
        arr = np.load(text_cache_path, mmap_mode="r")
        if arr.ndim != 2 or arr.shape[0] != len(data):
            raise ValueError(
                f"Text embedding cache shape {arr.shape} does not match N={len(data)}."
            )
        del arr
        cache_arg: Optional[Path] = text_cache_path
    else:
        cache_arg = None

    transform = Compose(
        [
            AddNodeFeature(),
            AddEdgeFeature(),
            AddAngleFeature(),
            GraphCollectingCached(["graph", "line_graph"], [target_name]),
        ]
    )
    subset_data = [data[i] for i in indices]
    return CachedCrystalGraphDataset(
        data=subset_data,
        transforms=transform,
        original_indices=list(indices),
        text_embedding_cache_path=cache_arg,
        cutoff=8.0,
        max_neighbors=12,
        line_graph=True,
        text_tokenizer=None,
    )


