def get_split_indices(
    n: int,
    training_config: Dict[str, Any],
) -> Tuple[List[int], List[int], List[int]]:
    ratio = training_config.get("split_ratio")
    counts = training_config.get("split_counts")

    if ratio is None and counts is None:
        print("[Warning] Checkpoint has no split config; using [0.8, 0.1, 0.1].")
        ratio = [0.8, 0.1, 0.1]

    train_idx, val_idx, test_idx = split_train_val_test(
        total_size=n,
        ratio_train_val_test=ratio if counts is None else None,
        n_train_val_test=counts,
        keep_order=False,
        split_seed=SPLIT_SEED,
    )
    return (
        list(train_idx or []),
        list(val_idx or []),
        list(test_idx or []),
    )


def select_eval_indices(
    split: str,
    train_idx: List[int],
    val_idx: List[int],
    test_idx: List[int],
    n: int,
) -> List[int]:
    name = split.strip().lower()
    if name == "train":
        return train_idx
    if name in {"val", "validation"}:
        return val_idx
    if name == "test":
        return test_idx
    if name == "all":
        return list(range(n))
    raise ValueError("EVAL_SPLIT must be train/val/test/all.")


def load_assignments(
    path: Path,
    data: List[Dict[str, Any]],
) -> Tuple[pd.DataFrame, str]:
    df = pd.read_csv(path)
    if "index" not in df.columns:
        raise KeyError("assignments.csv must contain an 'index' column.")

    cluster_candidates = [
        "fusiformer_cluster",
        "graph_cluster",
        "cluster",
    ]
    cluster_col = next((c for c in cluster_candidates if c in df.columns), None)
    if cluster_col is None:
        raise KeyError(
            f"Could not find cluster column. Tried {cluster_candidates}."
        )

    if df["index"].duplicated().any():
        raise ValueError("assignments.csv contains duplicate original indices.")

    expected = set(range(len(data)))
    actual = set(df["index"].astype(int).tolist())
    missing = expected - actual
    if missing:
        raise ValueError(
            f"assignments.csv is missing {len(missing)} dataset indices."
        )

    # Alignment check against original dataset e_form.
    if "e_form" in df.columns:
        check = df.set_index("index")["e_form"]
        y = np.array([float(item["e_form"]) for item in data], dtype=np.float64)
        aligned = check.loc[np.arange(len(data))].to_numpy(dtype=np.float64)
        max_diff = float(np.max(np.abs(y - aligned)))
        if max_diff > 1e-6:
            raise ValueError(
                "assignments.csv does not align with dataset JSON: "
                f"max |e_form difference|={max_diff:.6g}"
            )

    return df, cluster_col


