def path_from_signature(meta: Dict[str, Any], key: str) -> Optional[Path]:
    node = meta.get(key)
    if isinstance(node, dict) and node.get("path"):
        return Path(node["path"]).expanduser()
    return None


def resolve_required_paths(
    assignments_path: Path,
) -> Tuple[Path, Path, Path, Optional[Path], Dict[str, Any]]:
    meta = read_graph_cache_meta()

    checkpoint_path = resolve_path_like(CHECKPOINT_PATH_OVERRIDE)
    if checkpoint_path is None:
        checkpoint_path = path_from_signature(meta, "checkpoint")
    if checkpoint_path is None or not checkpoint_path.is_file():
        raise FileNotFoundError(
            "Cannot resolve the Base Fusiformer checkpoint. "
            "Set CHECKPOINT_PATH_OVERRIDE at the top of the script."
        )
    checkpoint_path = checkpoint_path.resolve()

    checkpoint = load_checkpoint(checkpoint_path)
    _, training_config = extract_model_state(checkpoint)

    data_path = resolve_path_like(DATA_PATH_OVERRIDE)
    if data_path is None:
        data_path = path_from_signature(meta, "data")
    if data_path is None and training_config.get("data_path"):
        data_path = resolve_path_like(training_config["data_path"])
    if data_path is None or not data_path.is_file():
        raise FileNotFoundError(
            "Cannot resolve dataset JSON. Set DATA_PATH_OVERRIDE."
        )
    data_path = data_path.resolve()

    text_cache = resolve_path_like(TEXT_EMBEDDING_CACHE_PATH_OVERRIDE)
    if text_cache is None and training_config.get("text_embedding_cache_path"):
        text_cache = resolve_path_like(training_config["text_embedding_cache_path"])

    if not GRAPH_OUT_CACHE_PATH.is_file():
        raise FileNotFoundError(
            f"graph_out cache not found: {GRAPH_OUT_CACHE_PATH}\n"
            "Run fusiformer_latent_eform_clustering.py first."
        )

    return data_path, checkpoint_path, GRAPH_OUT_CACHE_PATH.resolve(), text_cache, meta


